// VisionFive2 (昉·星光2, SoC: StarFive JH7110) 的板级资源描述。
// 与 platform/qemu-virt-riscv64/platform.h 结构相同、仅数值与部分设备选型不同:
// 结构相同说明 platform 提供了统一抽象界面, 数值不同说明差异被隔离在 platform 层。
// 若当初用 #ifdef 把地址散在 kernel/ 里, 加一块板子要改 trap/mem/fs/lib 多处;
// 现在只需新增一个目录 + 一个头文件。
#ifndef __PLATFORM_H__
#define __PLATFORM_H__

/* --------------------------------------------------------------------------
 * 1. 物理内存布局
 * -------------------------------------------------------------------------- */

/* JH7110 的 DRAM 从 0x40000000 开始 (QEMU virt 是 0x80000000)。
 * 这是最显眼的一处差异: 同一个 ISA, 同一份内核代码,
 * 仅仅因为换了 SoC, 内存基地址就完全不同。 */
#define PLAT_DRAM_BASE      0x40000000UL

/* VisionFive2 板载 2GB/4GB/8GB 三种版本。
 * 这里保守地只使用前 128MB 做物理页管理, 原因:
 *   1. 教学内核不需要那么大内存, 128MB 足够跑完所有实验
 *   2. U-Boot 可能把内核/initrd 放在高端地址, 小范围管理更安全
 * 学生可以自己改大这个值做实验, 但要同时保证不与保留区重叠。 */
#define PLAT_DRAM_SIZE      (128UL * 1024 * 1024)

/* OpenSBI 占 0x40000000 起, 运行完跳转到 0x40200000。 */
#define PLAT_KERNEL_BASE    0x40200000UL
#define PLAT_FIRMWARE_BASE  0x40000000UL

/* --------------------------------------------------------------------------
 * 2. CPU 拓扑
 * -------------------------------------------------------------------------- */

/* JH7110 是 4+1 核: 四个 U74 应用核 + 一个 S7 监控核。
 *   监控核 (hart 0) 被 U-Boot 自己占用, 内核不应该去触碰它。
 *   因此内核可用的 hart 是 1, 2, 3, 4 —— 共 4 个。
 *
 * 对比 QEMU: 那边四个 hart 全都能用, 启动核是 0。
 * 这个差异如果写错, 症状是 "内核在真机上启动后随机卡死",
 * 因为内核可能去启动一个正在被 U-Boot 使用的核。 */
#define PLAT_NCPU           4

/* 内核使用的第一个 hart。U-Boot 会把内核跑在 hart 1 上。
 * arch/riscv64/smp/cpu.c 用它做 hartid <-> cpuid 的换算。 */
#define PLAT_BOOT_HART      1

/* 内核可用的 hart id 范围, 用于校验 a0 传进来的 hartid 是否合法。 */
#define PLAT_HART_MIN       1
#define PLAT_HART_MAX       4

/* --------------------------------------------------------------------------
 * 3. 中断控制器
 * -------------------------------------------------------------------------- */

/* JH7110 同样使用 SiFive PLIC, 但基地址与 QEMU 不同。
 *
 * 关键教学点: drivers/irqchip/plic.c 的代码一行都不用改!
 * 因为它的实现只依赖 PLAT_PLIC_BASE 这些宏, 而宏由 platform 层提供。
 * 这就是"驱动描述设备协议, 平台描述设备位置"带来的复用。 */
#define PLAT_PLIC_BASE      0xc000000UL
#define PLAT_PLIC_SIZE      0x4000000UL
#define PLAT_TIMER_INTERVAL 400000UL

/* --------------------------------------------------------------------------
 * 5. 串口 (console)
 * -------------------------------------------------------------------------- */

/* JH7110 的 UART0, 同样是 16550 兼容控制器 —— 所以驱动可以直接复用。
 * 但地址和输入时钟不同, 分频系数需要按 PLAT_UART0_CLOCK 重新计算,
 * 否则真机串口会输出乱码 (这是移植时最常见的第一个 bug)。 */
#define PLAT_UART0_BASE     0x10000000UL
#define PLAT_UART0_IRQ      32
#define PLAT_UART0_CLOCK    24000000UL  /* JH7110 UART 输入时钟 24MHz */

/* --------------------------------------------------------------------------
 * 6. 块设备 (磁盘)
 * -------------------------------------------------------------------------- */

/* VisionFive2 没有 VirtIO, 它用真实的 microSD 卡。
 * 控制器是 Synopsys DesignWare MSHC (SDHCI 兼容)。
 *
 * 这里的架构意义:
 *   QEMU:  virtio_blk  -> 提供 block_device 接口
 *   VF2:   sdhci       -> 提供同一个 block_device 接口
 *   上层 fs/ 只调用 block_read()/block_write(),
 *   所以文件系统代码在两个平台上是完全相同的。
 *   （2025 版本里 fs/virtio.c 直接躺在 fs/ 目录下, 这是层次倒置,
 *     新版把它移到了 drivers/block/, 并且用 block_device 隔开。） */
#define PLAT_SDIO0_BASE     0x16000000UL
#define PLAT_SDIO0_IRQ      0          /* 本课程使用轮询模式, 不使用 SD 中断 */

/* SD 卡上存放文件系统镜像的分区偏移。
 * 注意这里用的是"分区内偏移"的概念, 而不是 2025 版本里那种
 * "前 20GB 给 disk.img" 的裸 dd 魔法数字。 */
#define PLAT_SDCARD_FS_OFFSET   0UL

/* --------------------------------------------------------------------------
 * 7. 平台标识 (仅供调试打印)
 * -------------------------------------------------------------------------- */
#define PLAT_NAME           "visionfive2"

#endif /* __PLATFORM_H__ */
